/**
 * Refreshes src/modules/auth/disposable-domains.data.ts from the community list of throwaway email domains
 * (github.com/disposable-email-domains/disposable-email-domains, public domain / CC0). Run now and then:
 *
 *   node scripts/update-disposable-domains.mjs
 *
 * Review the diff before committing: a real provider on the list would stop real people signing up (put it in
 * ALLOWED in disposable-email.ts instead of editing the data file by hand).
 */
import { writeFileSync } from 'node:fs';

const SOURCE =
  'https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf';
const OUT = new URL('../src/modules/auth/disposable-domains.data.ts', import.meta.url);

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`Could not fetch the list: HTTP ${res.status}`);
const domains = [
  ...new Set(
    (await res.text())
      .split('\n')
      .map((l) => l.trim().toLowerCase())
      .filter((l) => /^[a-z0-9.-]+\.[a-z0-9-]+$/.test(l)),
  ),
].sort();
if (domains.length < 1000)
  throw new Error(`Only ${domains.length} domains: refusing to write a suspiciously short list.`);

const today = new Date().toISOString().slice(0, 10);
writeFileSync(
  OUT,
  `// Generated by scripts/update-disposable-domains.mjs on ${today}: do not edit by hand.\n` +
    `// Source: github.com/disposable-email-domains/disposable-email-domains (public domain, CC0). ${domains.length} domains.\n` +
    `export const DISPOSABLE_DOMAINS = \`\n${domains.join('\n')}\n\`;\n`,
);
process.stdout.write(`Wrote ${domains.length} domains.\n`);
